"""Generate P2 Android labels from the same ARB source as Flutter."""
import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
LOCALES = {"en": "values", "vi": "values-vi", "es": "values-es",
           "pt_BR": "values-pt-rBR", "fr": "values-fr", "de": "values-de",
           "id": "values-in", "ja": "values-ja", "ko": "values-ko",
           "zh_Hans": "values-b+zh+Hans", "hi": "values-hi", "ar": "values-ar"}
KEYS = {"p2_edit_video": "editVideo", "p2_edit_photo": "editPhoto",
        "p2_preview_unavailable": "thisVideoCannotBePlayedOrAccess",
        "p2_back": "onboardingBack"}

CAPTURE_LABELS = (
    'Recording', 'Paused', 'Saving', 'Pause', 'Resume', 'Stop', 'Screenshot saved', 'Video saved',
    'Draw on screen', 'Exit drawing', 'Undo drawing', 'Clear drawing', 'Drawing color and width',
    'Facecam options', 'Switch camera', 'Show controls in video', 'Hide controls',
    'Small', 'Normal', 'Large', 'None', 'Grayscale', 'Sepia', 'Orange', 'Red', 'White', 'Blue',
    'Not supported by this device or the selected mode',
)


def synchronize():
    english = json.loads((ROOT / 'lib/l10n/app_en.arb').read_text(encoding='utf8'))
    source = {v: k for k, v in english.items() if not k.startswith('@') and isinstance(v, str)}
    capture = {f'capture_label_{index}': source[label] for index, label in enumerate(CAPTURE_LABELS)}
    for locale, folder in LOCALES.items():
        data = json.loads((ROOT / f"lib/l10n/app_{locale}.arb").read_text(encoding="utf8"))
        lines = ["<!-- Generated by tool/sync_p2_native_l10n.py from ARB. -->", "<resources>"]
        for resource, key in KEYS.items():
            text = escape(data[key].replace("''", "'")).replace("'", "\\'").replace('"', '\\"')
            lines.append(f'    <string name="{resource}" formatted="false">{text}</string>')
        lines.append("</resources>")
        target = ROOT / f"android/app/src/main/res/{folder}/p2_strings.xml"
        target.parent.mkdir(exist_ok=True)
        target.write_text("\n".join(lines) + "\n", encoding="utf8")
        lines = ['<!-- Generated by tool/sync_p2_native_l10n.py from ARB. -->', '<resources>']
        for resource, key in capture.items():
            value = escape(data[key].replace("''", "'")).replace("'", "\\'").replace('"', '\\"')
            lines.append(f'    <string name="{resource}" formatted="false">{value}</string>')
        lines.append('</resources>')
        (target.parent / 'capture_strings.xml').write_text('\n'.join(lines) + '\n', encoding='utf8')
    bindings = '\n'.join(f'        {json.dumps(label)} to R.string.capture_label_{index},' for index, label in enumerate(CAPTURE_LABELS))
    kotlin = '''// Generated by tool/sync_p2_native_l10n.py; translations belong to ARB.
package com.xrecorder.xrecorder.recording

import android.content.Context
import com.xrecorder.xrecorder.R
import com.xrecorder.xrecorder.media.P2Locale

internal object CaptureText {
    private val labels = mapOf(
''' + bindings + '''
    )
    private val aliases = mapOf(
        "Pause recording" to "Pause", "Resume recording" to "Resume", "Stop recording" to "Stop",
        "Small camera" to "Small", "Normal camera" to "Normal", "Large camera" to "Large",
        "No camera effect" to "None", "Grayscale camera" to "Grayscale", "Sepia camera" to "Sepia",
        "Screen recording" to "Recording"
    )
    fun text(base: Context, source: String): String {
        val key = aliases[source] ?: source
        val resource = labels[key] ?: return source
        return P2Locale.context(base).getString(resource)
    }
}
'''
    (ROOT / 'android/app/src/main/kotlin/com/xrecorder/xrecorder/recording/CaptureText.kt').write_text(kotlin, encoding='utf8')


if __name__ == "__main__":
    synchronize()
    print("Synchronized 12 native UI resource locales.")
