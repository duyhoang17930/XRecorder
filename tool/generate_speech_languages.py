"""Maintenance generator: pinned Whisper language table + Babel/CLDR display names.

Generated Dart/ARB data are checked in; the app never depends on Python or Babel.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'build/verification/task07/python'))
from babel import Locale, UnknownLocaleError

LOCALES = ['en','vi','es','pt_BR','fr','de','id','ja','ko','zh_Hans','hi','ar']
upstream = ROOT / 'android/app/src/main/cpp/third_party/whisper.cpp/src/whisper.cpp'
table = upstream.read_text(encoding='utf8').split(' g_lang = {', 1)[1].split('};', 1)[0]
languages = sorted([(int(i), code, name) for code, i, name in re.findall(r'\{\s*"([a-z]+)"\s*,\s*\{\s*(\d+)\s*,\s*"([a-z ]+)"', table)])
assert len(languages) == 100 and languages[-1] == (99, 'yue', 'cantonese')

def name(code, locale, fallback):
    alias = {'jw':'jv'}.get(code, code)
    try:
        return str(Locale.parse(locale).languages.get(alias) or fallback)
    except UnknownLocaleError:
        return fallback

def dart(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')

lines = ["import '../../l10n/generated/app_localizations.dart';", '',
    '// Generated by tool/generate_speech_languages.py from vendored whisper.cpp v1.9.5.',
    '// Names: Babel 2.17 / Unicode CLDR. See assets/licenses/CLDR-LICENSE.txt.',
    '// Verified Tiny/Base/Small-q5_1 vocab=51865 => 99 languages; yue needs a newer model.',
    'class SpeechLanguage {',
    '  const SpeechLanguage(this.code, this.nativeCode, this.englishName, this.nativeName, {this.available = true});',
    '  final String code, englishName, nativeName;', '  final int nativeCode;', '  final bool available;',
    '  String displayName(AppLocalizations strings) => SpeechLanguages.displayName(strings, code);', '}', '',
    'abstract final class SpeechLanguages {',
    '  static const modelLanguageCount = 99;',
    '  static const auto = SpeechLanguage("auto", -1, "Auto Detect", "Auto Detect");',
    '  static const values = <SpeechLanguage>[auto,']
for i, code, english in languages:
    english = name(code, 'en', english.title())
    native = name(code, {'jw':'jv'}.get(code, code), english) if code not in ('haw','yue') else {'haw':'ʻŌlelo Hawaiʻi','yue':'粵語'}[code]
    lines.append(f'    SpeechLanguage({dart(code)}, {i}, {dart(english)}, {dart(native)}, available: {str(i<99).lower()}),')
lines += ['  ];', '  static SpeechLanguage? find(String code) {', '    for (final language in values) { if (language.code == code) return language; }', '    return null;', '  }', '  static bool supports(String code) => find(code)?.available == true;',
    '  static String displayName(AppLocalizations strings, String code) => switch (code) {', '    "auto" => strings.autoDetect,']
for i, code, english in languages:
    lines.append(f'    {dart(code)} => strings.speechLanguage{code.title()},')
lines += ['    _ => code,', '  };', '}', '']
(ROOT/'lib/features/editor/speech_languages.dart').write_text('\n'.join(lines), encoding='utf8')
for locale in LOCALES:
    path = ROOT / f'lib/l10n/app_{locale}.arb'
    data = json.loads(path.read_text(encoding='utf8'))
    for i, code, english in languages:
        key = 'speechLanguage'+code.title()
        data[key] = name(code, locale, english.title()).replace("'", "''")
        if locale == 'en': data['@'+key] = {'description':f'CLDR display name for Whisper language {code}, native engine ID {i}. Proper language name; speech language is independent of app locale.'}
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n', encoding='utf8')
for parent, child in [('pt','pt_BR'),('zh','zh_Hans')]:
    path = ROOT / f'lib/l10n/app_{parent}.arb'
    data=json.loads((ROOT/f'lib/l10n/app_{child}.arb').read_text(encoding='utf8'));data['@@locale']=parent
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n', encoding='utf8')
print('Generated 100 engine entries: 99 available + unavailable Cantonese, plus Auto Detect; CLDR names in 12 locales.')
